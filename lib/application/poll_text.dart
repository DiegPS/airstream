final _space = RegExp(r'\s+', unicode: true);
final _mark = RegExp(r'\p{M}', unicode: true);
final _diacritic = RegExp(r'\p{Diacritic}', unicode: true);
final _accentFolding = {
  for (final entry in _accentedLetters.entries)
    for (final rune in entry.value.runes) String.fromCharCode(rune): entry.key,
};

/// Keeps punctuation and folds canonical accents, case and whitespace.
String normalizePollText(String text) {
  final folded = StringBuffer();
  for (final rune in text.toLowerCase().runes) {
    final letter = String.fromCharCode(rune);
    if (rune > 127 && _mark.hasMatch(letter) && _diacritic.hasMatch(letter)) {
      continue;
    }
    folded.write(_accentFolding[letter] ?? letter);
  }
  return folded.toString().replaceAll(_space, ' ').trim();
}

