import 'package:airstream/l10n/generated/app_localizations.dart';

class SettingsSearchEntry {
  const SettingsSearchEntry(this.id, this.tab, this.title, this.labels,
      {this.fallback});
  final String id;
  final int tab;
  final String title;
  final List<String> labels;
  final String? fallback;
}

String normalizeSettingsSearch(String text) {
  const accented = {
    'á': 'a',
    'é': 'e',
    'í': 'i',
    'ó': 'o',
    'ú': 'u',
    'ü': 'u',
    'ñ': 'n'
  };
  return text
      .toLowerCase()
      .replaceAllMapped(RegExp('[áéíóúüñ]'), (match) => accented[match[0]]!)
      .replaceAll(RegExp(r'[\u0300-\u036f]'), '');
}

List<String> settingsTabLabels(AppLocalizations l) => [
      l.connections,
      l.ttsAndVoice,
      l.appearance,
      l.obsAndOverlay,
      l.liveTab,
      l.ruleLabel('krules'),
      l.templatesTitle,
      l.systemTab,
    ];

List<SettingsSearchEntry> searchSettings(AppLocalizations l, String query) {
  final terms = normalizeSettingsSearch(query.trim()).split(RegExp(r'\s+'));
  if (terms.singleOrNull == '') return const [];
  final tabs = settingsTabLabels(l);
  return [
    for (final entry in _index(l))
      if (terms.every(normalizeSettingsSearch(
              [entry.title, tabs[entry.tab], ...entry.labels].join(' '))
          .contains))
        entry,
  ];
}

